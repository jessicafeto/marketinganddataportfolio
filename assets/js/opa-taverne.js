(function () {
  'use strict';

  var nav = document.querySelector('.opa-nav');
  var navLinks = document.querySelector('.opa-nav-links');
  var navToggle = document.querySelector('.opa-nav-toggle');

  function onScroll() {
    if (window.scrollY > 40) {
      nav.classList.add('is-solid');
    } else {
      nav.classList.remove('is-solid');
    }
  }
  window.addEventListener('scroll', onScroll, { passive: true });
  onScroll();

  if (navToggle && navLinks) {
    navToggle.addEventListener('click', function () {
      navLinks.classList.toggle('is-open');
      navToggle.classList.toggle('is-active');
    });
    navLinks.querySelectorAll('a').forEach(function (a) {
      a.addEventListener('click', function () {
        navLinks.classList.remove('is-open');
        navToggle.classList.remove('is-active');
      });
    });
  }

  // Reveal on scroll
  var revealEls = document.querySelectorAll('.opa-reveal, .opa-reveal-stagger');
  var io = new IntersectionObserver(
    function (entries) {
      entries.forEach(function (entry) {
        if (entry.isIntersecting) {
          entry.target.classList.add('is-visible');
          io.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.15, rootMargin: '0px 0px -60px 0px' }
  );
  revealEls.forEach(function (el) { io.observe(el); });

  // Subtle hero parallax (rAF-throttled for smoothness)
  var heroImg = document.querySelector('.opa-hero-media img');
  var reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  if (heroImg && !reduceMotion) {
    var parallaxTicking = false;
    window.addEventListener(
      'scroll',
      function () {
        if (parallaxTicking) return;
        parallaxTicking = true;
        requestAnimationFrame(function () {
          var y = window.scrollY;
          if (y < window.innerHeight) {
            heroImg.style.transform = 'scale(1.08) translateY(' + y * 0.12 + 'px)';
          }
          parallaxTicking = false;
        });
      },
      { passive: true }
    );
  }

  // Magnetic button hover
  if (!reduceMotion && window.matchMedia('(hover: hover)').matches) {
    document.querySelectorAll('.opa-btn').forEach(function (btn) {
      btn.addEventListener('mousemove', function (e) {
        var rect = btn.getBoundingClientRect();
        var relX = e.clientX - rect.left - rect.width / 2;
        var relY = e.clientY - rect.top - rect.height / 2;
        btn.style.transition = 'transform 0.25s cubic-bezier(0.16, 1, 0.3, 1)';
        btn.style.transform = 'translate(' + (relX * 0.16).toFixed(1) + 'px, ' + (relY * 0.35 - 2).toFixed(1) + 'px)';
      });
      btn.addEventListener('mouseleave', function () {
        btn.style.transition = 'transform 0.5s cubic-bezier(0.16, 1, 0.3, 1)';
        btn.style.transform = '';
      });
    });
  }

  // Gallery lightbox
  var lightbox = document.querySelector('.opa-lightbox');
  var lightboxImg = lightbox ? lightbox.querySelector('img') : null;
  var galleryItems = document.querySelectorAll('.opa-gallery-item');

  galleryItems.forEach(function (item) {
    item.addEventListener('click', function () {
      var src = item.querySelector('img').getAttribute('src');
      var alt = item.querySelector('img').getAttribute('alt');
      if (lightbox && lightboxImg) {
        lightboxImg.setAttribute('src', src);
        lightboxImg.setAttribute('alt', alt);
        lightbox.classList.add('is-open');
      }
    });
  });

  function closeLightbox() {
    if (lightbox) lightbox.classList.remove('is-open');
  }

  var lightboxClose = document.querySelector('.opa-lightbox-close');
  if (lightboxClose) lightboxClose.addEventListener('click', closeLightbox);
  if (lightbox) {
    lightbox.addEventListener('click', function (e) {
      if (e.target === lightbox) closeLightbox();
    });
  }
  window.addEventListener('keydown', function (e) {
    if (e.key === 'Escape') closeLightbox();
  });

  // ---------------- Digital menu ----------------
  var menuModal = document.querySelector('.opa-menu-modal');
  if (menuModal) {
    var tabsEl = menuModal.querySelector('.opa-menu-book-tabs');
    var pagesEl = menuModal.querySelector('.opa-menu-book-pages');

    OPA_MENU_DATA.forEach(function (cat, i) {
      var tab = document.createElement('button');
      tab.className = 'opa-menu-tab' + (i === 0 ? ' is-active' : '');
      tab.type = 'button';
      tab.dataset.cat = cat.id;
      tab.textContent = cat.label;
      tabsEl.appendChild(tab);

      var panel = document.createElement('div');
      panel.className = 'opa-menu-panel' + (i === 0 ? ' is-active' : '');
      panel.dataset.cat = cat.id;

      var head = document.createElement('div');
      head.className = 'opa-menu-panel-head';
      head.innerHTML =
        '<h3>' + cat.label + '</h3><span>' + cat.sub + '</span>';
      panel.appendChild(head);

      cat.items.forEach(function (item) {
        var row = document.createElement('div');
        row.className = 'opa-menu-real-row';
        row.innerHTML =
          '<div class="opa-menu-real-top">' +
            '<span class="opa-menu-real-name">' + item[0] + '</span>' +
            '<span class="opa-menu-real-leader"></span>' +
            '<span class="opa-menu-real-price">' + item[2] + '&nbsp;&euro;</span>' +
          '</div>' +
          (item[1] ? '<span class="opa-menu-real-desc">' + item[1] + '</span>' : '');
        panel.appendChild(row);
      });

      pagesEl.appendChild(panel);
    });

    tabsEl.addEventListener('click', function (e) {
      var btn = e.target.closest('.opa-menu-tab');
      if (!btn) return;
      setActiveCategory(btn.dataset.cat);
    });

    function setActiveCategory(catId) {
      tabsEl.querySelectorAll('.opa-menu-tab').forEach(function (t) {
        t.classList.toggle('is-active', t.dataset.cat === catId);
      });
      pagesEl.querySelectorAll('.opa-menu-panel').forEach(function (p) {
        p.classList.toggle('is-active', p.dataset.cat === catId);
      });
      pagesEl.scrollTop = 0;
      var activeTab = tabsEl.querySelector('.opa-menu-tab.is-active');
      if (activeTab && activeTab.scrollIntoView) {
        activeTab.scrollIntoView({ block: 'nearest', inline: 'center', behavior: 'smooth' });
      }
    }

    function openMenuModal(catId) {
      if (catId) setActiveCategory(catId);
      menuModal.classList.add('is-open');
      document.documentElement.classList.add('opa-no-scroll');
    }

    function closeMenuModal() {
      menuModal.classList.remove('is-open');
      document.documentElement.classList.remove('opa-no-scroll');
    }

    document.querySelectorAll('[data-menu-open]').forEach(function (trigger) {
      trigger.addEventListener('click', function (e) {
        e.preventDefault();
        openMenuModal(trigger.dataset.menuOpen || null);
      });
    });

    var menuModalClose = menuModal.querySelector('.opa-menu-book-close');
    if (menuModalClose) menuModalClose.addEventListener('click', closeMenuModal);
    menuModal.addEventListener('click', function (e) {
      if (e.target === menuModal) closeMenuModal();
    });
    window.addEventListener('keydown', function (e) {
      if (e.key === 'Escape') closeMenuModal();
    });
  }

  // ---------------- Reservation form ----------------
  var reserveForm = document.getElementById('opa-reserve-form');
  if (reserveForm) {
    var dateInput = document.getElementById('res-date');
    if (dateInput) {
      var today = new Date();
      var pad = function (n) { return String(n).padStart(2, '0'); };
      dateInput.min = today.getFullYear() + '-' + pad(today.getMonth() + 1) + '-' + pad(today.getDate());
    }

    reserveForm.addEventListener('submit', function (e) {
      e.preventDefault();
      if (!reserveForm.checkValidity()) {
        reserveForm.reportValidity();
        return;
      }

      var name = document.getElementById('res-name').value.trim();
      var guests = document.getElementById('res-guests').value;
      var dateVal = document.getElementById('res-date').value;
      var time = document.getElementById('res-time').value;

      var dateFormatted = dateVal;
      if (dateVal) {
        var d = new Date(dateVal + 'T00:00:00');
        dateFormatted = d.toLocaleDateString('en-GB', { weekday: 'long', day: 'numeric', month: 'long' });
      }

      var successNameEl = document.getElementById('opa-success-name');
      var successDetailEl = document.getElementById('opa-success-detail');
      if (successNameEl) successNameEl.textContent = name ? ', ' + name : '';
      if (successDetailEl) {
        successDetailEl.textContent =
          'Your table for ' + guests + (guests === '1' ? ' guest' : ' guests') +
          ' on ' + dateFormatted + ' at ' + time + ' has been noted.';
      }

      var successEl = document.getElementById('opa-reserve-success');
      reserveForm.hidden = true;
      if (successEl) {
        successEl.hidden = false;
        successEl.classList.add('opa-anim-in');
      }
    });
  }
})();
